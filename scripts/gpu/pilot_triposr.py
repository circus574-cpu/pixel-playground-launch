assert torch.cuda.is_available()
# Deterministic gray compositing is model preprocessing; no creative image modification.
im=Image.open(a.image).convert('RGBA');alpha=np.asarray(im,dtype=np.float32)/255
rgb=alpha[:,:,:3]*alpha[:,:,3:4]+.5*(1-alpha[:,:,3:4]);content=Image.fromarray((rgb*255).astype('uint8'))
# Preserve character proportions: square padding, never stretch a portrait into a square.
side=round(max(content.size)/.90);im=Image.new('RGB',(side,side),(128,128,128));im.paste(content,((side-content.width)//2,(side-content.height)//2));im.save(out/'inference-input.png')
torch.manual_seed(42);start=time.monotonic();model=TSR.from_pretrained(str(models),config_name='config.yaml',weight_name='model.ckpt');model.renderer.set_chunk_size(8192);model.to('cuda')
print('Running TripoSR inference',flush=True)
with torch.no_grad():codes=model([im],device='cuda')
print('Extracting 384-grid mesh',flush=True)
mesh=model.extract_mesh(codes,False,resolution=384)[0]
mesh.export(out/'sage-shape-untextured.ply')
torch.save(codes.detach().cpu(),out/'reconstruction-code.pt')
