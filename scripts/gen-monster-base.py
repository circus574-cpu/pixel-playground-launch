"""Writes src/game/monsters/base.generated.ts from art/production/enemies/roster.json (owner bestiary, 22.10.2026)."""
import json
roster = json.load(open("art/production/enemies/roster.json"))["monsters"]
out = ["/* Generated by scripts/gen-monster-base.py from art/production/enemies/roster.json. Do not edit by hand. */",
       'import type { WorldId } from "../world/races";', "",
       "export type MonsterBase = {",
       "  id: string; world: WorldId; name: string; level: number; hp: number; atk: number; def: number; xp: number;",
       "  speed: number; range: number; agro: number; archetype: string; size: string; loot: string[];",
       "};", "", "export const MONSTER_BASE: MonsterBase[] = ["]
for e in roster:
    loot = [x.strip() for x in e["loot"].split(",")]
    s = e["stats"]
    out.append("  " + json.dumps({"id": e["id"], "world": e["world"], "name": e["name"], "level": e["level"], "hp": s["hp"], "atk": s["atk"],
                                  "def": s["def"], "xp": s["xp"], "speed": e["speed"], "range": e["range"], "agro": e["agro"],
                                  "archetype": e["archetype"], "size": e["size"], "loot": loot}, ensure_ascii=False) + ",")
out.append("];")
open("src/game/monsters/base.generated.ts", "w").write("\n".join(out) + "\n")
print(len(roster))
