import json
d=json.load(open('docs/design/data/character-progression-1-20.json'))
out=['/* Generated by scripts/gen-kit-nodes.py from docs/design/data/character-progression-1-20.json (owner annex 22.10.2026). Do not edit by hand. */',
'import type { RaceId } from "../world/races";',
'import type { KitNodeData, RaceBase } from "./types";','']
out.append('export const RACE_BASE: Record<RaceId, { base: RaceBase; perLevel: RaceBase; mechanic: string; role: string; start: string }> = {')
for k,r in d['races'].items():
    out.append('  %s: { base: %s, perLevel: %s, mechanic: %s, role: %s, start: %s },'%(k,json.dumps(r['base']),json.dumps(r['perLevel']),json.dumps(r['raceMechanic'],ensure_ascii=False),json.dumps(r['role'],ensure_ascii=False),json.dumps(r['startingAbility'],ensure_ascii=False)))
out.append('};')
out.append('')
out.append('export const BRANCH_NAMES: Record<RaceId, Record<"A" | "B" | "C", string>> = {')
for k,r in d['races'].items():
    out.append('  %s: %s,'%(k,json.dumps({b:v['name'] for b,v in r['skillBranches'].items()},ensure_ascii=False)))
out.append('};')
out.append('')
out.append('export const KIT_NODES: Record<RaceId, KitNodeData[]> = {')
for k,r in d['races'].items():
    out.append('  %s: ['%k)
    for n in r['nodes']:
        ex=[p for p in r['exclusiveChoices'] if n['id'] in p]
        excl=[x for x in ex[0] if x!=n['id']][0] if ex else None
        node={'id':n['id'],'name':n['name'],'type':n['type'],'minLevel':n['minLevel'],'requires':n['requiresAny'],'text':n['effect']}
        if excl: node['excludes']=excl
        out.append('    %s,'%json.dumps(node,ensure_ascii=False))
    out.append('  ],')
out.append('};')
open('src/game/kit/nodes.generated.ts','w').write('\n'.join(out)+'\n')
print('ok')
