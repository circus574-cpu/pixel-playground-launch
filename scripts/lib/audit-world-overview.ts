/** Read-only inventory of the exact V2 overview inputs. No server, storage or GPU access. */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { loadOverview, OVERVIEW_INDEX } from "../../src/components/admin/world-overview/loader";
import { questEntries, overviewCatalog } from "../../src/components/admin/world-overview/model";
import { emptyAdminWorldOverrides } from "../../src/game/world/adminWorldStore";
async function main() {
  globalThis.fetch = async (input, options) => {
    if (options?.signal?.aborted) throw new DOMException("Aborted", "AbortError");
    const pathname = new URL(
      input instanceof Request ? input.url : String(input),
      "http://localhost",
    ).pathname;
    if (!pathname.startsWith("/game/worlds/superior-v2/")) throw Error("Unexpected inventory path");
    return new Response(readFileSync("public" + pathname), { status: 200 });
  };
  const ov = emptyAdminWorldOverrides(),
    lands = await loadOverview(ov, new AbortController().signal, () => {}),
    entries = lands.flatMap((l) => l.entries),
    q = questEntries(lands, ov);
  const sourceFiles = [
    "src/components/admin/AdminWorldOverview.tsx",
    "src/components/admin/world-overview/model.ts",
    "src/components/admin/world-overview/loader.ts",
    "src/components/admin/world-overview/OverviewCanvas.tsx",
    "src/components/admin/world-overview/PointFacts.tsx",
    "src/components/admin/world-overview/overview.css",
    "src/game/admin/worldOverviewCatalog.generated.json",
    "src/game/admin/worldDevelopment.generated.json",
    "scripts/lib/build-world-development.ts",
    "src/routes/admin.tsx",
    "e2e/admin-world-overview.spec.ts",
  ];
  const result = {
    format: "ki-admin-world-overview-1",
    sourceSha: execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim(),
    dirty: !!execFileSync("git", ["status", "--porcelain"], { encoding: "utf8" }).trim(),
    world: "superior-v2",
    worldRevision: OVERVIEW_INDEX.revision,
    sourceHashes: Object.fromEntries(
      sourceFiles.map((p) => [p, createHash("sha256").update(readFileSync(p)).digest("hex")]),
    ),
    counts: {
      lands: lands.length,
      spawns: entries.filter((e) => e.layer === "spawns").length,
      npcs: entries.filter((e) => e.layer === "npcs").length,
      questsV2: q.quests.length,
      nativeQuestTypes: Object.keys(overviewCatalog.tutorialQuests).length,
      secrets: entries.filter((e) => e.layer === "secrets").length,
      dungeonEntrances: entries.filter((e) => e.layer === "dungeons").length,
      uniqueReservedDungeonInstances: new Set(
        lands.flatMap((l) => l.source.dungeons.map((d) => d.instanceId)),
      ).size,
      questMarkers: q.entries.length,
      unmappedQuestTargets: q.unmapped.length,
      developmentActivities: new Set(
        entries.filter((e) => e.layer === "development").map((e) => e.sourceId),
      ).size,
      developmentMarkers: entries.filter((e) => e.layer === "development").length,
      items: overviewCatalog.items.length,
      recipes: overviewCatalog.recipes.length,
      dialogues: Object.keys(overviewCatalog.dialogues).length,
    },
    lands: lands.map((l) => ({
      id: l.info.id,
      name: l.info.name,
      width: l.info.width,
      height: l.info.height,
      worldSha256: l.info.worldSha256,
      counts: Object.fromEntries(
        [...new Set(l.entries.map((e) => e.layer))].map((k) => [
          k,
          l.entries.filter((e) => e.layer === k).length,
        ]),
      ),
      rejectedSpawns: l.rejected,
    })),
    unmappedQuestTargets: q.unmapped,
    notes: [
      "Static authored points and published/draft definition overlays; not live actors or an account quest state.",
      "Room-local coordinates never projected directly onto the planet; outdoor building doors anchor interior NPC markers.",
      "Reserved dungeon entrances and raw geographic/resource annotations are data-only. No dungeon travel is implied.",
      "Chunk scenery is a bounded view of authored package objects, not a duplicate Phaser renderer or particle simulation.",
      "The catalogue snapshot is regenerated by scripts/lib/build-world-overview.ts and checked against runtime definitions in unit tests.",
    ],
  };
  writeFileSync(
    process.argv[2] ?? "/tmp/ki-admin-world-inventory.json",
    JSON.stringify(result, null, 2) + "\n",
  );
  console.log(JSON.stringify(result.counts));
}
void main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
