import { writeFileSync } from "node:fs";
import { ITEM_CATALOG } from "../src/game/items/catalog";
import { CRAFTING_RECIPES } from "../src/game/items/recipes";
import { MATERIALS } from "../src/game/monsters/materials";
import { lootLevel } from "../src/game/items/loot";
import type { CraftingRecipe, CraftingStation } from "../src/game/items/types";

const hasRecipe = new Set(CRAFTING_RECIPES.map((r) => r.resultItemId));
const better = ITEM_CATALOG.filter(
  (i) =>
    i.category !== "quest" &&
    ["rare", "epic", "legendary"].includes(i.rarity) &&
    !hasRecipe.has(i.id),
);
const mats = Object.values(MATERIALS);
const stationOf = (cat: string): CraftingStation =>
  cat === "consumable"
    ? "alchemy"
    : cat === "artifact" || cat === "buff" || cat === "amulet" || cat === "ring"
      ? "runic"
      : cat === "tool"
        ? "cyber_fabricator"
        : "forge";
const costOf = (rarity: string, level: number) =>
  (rarity === "legendary" ? 400 : rarity === "epic" ? 150 : 50) + level * 10;

const extra: CraftingRecipe[] = [];
for (const item of better) {
  const level = lootLevel(item);
  // materiały z potworów w oknie poziomów przedmiotu
  const near = mats.filter((m) => m.level >= level - 4 && m.level <= level + 2);
  const pool = near.length ? near : mats.filter((m) => m.level <= level + 2);
  if (!pool.length) continue;
  const nIng = item.rarity === "legendary" ? 4 : item.rarity === "epic" ? 3 : 2;
  const picked = [...pool].sort((a, b) => b.level - a.level).slice(0, nIng);
  const ingredients = picked.map((m, i) => ({
    itemId: m.id,
    count: item.rarity === "legendary" ? 3 + (i % 2) : item.rarity === "epic" ? 2 + (i % 2) : 2,
  }));
  extra.push({
    id: `rec-gen-${item.id}`,
    name: `Wytworzenie: ${item.name}`,
    station: stationOf(item.category),
    requiredLevel: Math.max(1, level),
    craftingCostCoins: costOf(item.rarity, level),
    ingredients,
    resultItemId: item.id,
    resultCount: 1,
    source: "repo",
  });
}
const body = extra.map((r) => "  " + JSON.stringify(r)).join(",\n");
writeFileSync(
  "../src/game/items/recipes.extra.ts",
  `/* Generated by scripts/gen-item-recipes.ts (system ekonomii 12.11.2026): receptury dla lepszych przedmiotów\n   (rare/epic/legendary), które nie miały receptury. Drop obejmuje tylko słabe przedmioty, więc\n   lepszy sprzęt musi być zdobywalny z craftu. Nie edytować ręcznie — regenerować generatorem. */\nimport type { CraftingRecipe } from "./types";\n\nexport const EXTRA_RECIPES: CraftingRecipe[] = [\n${body},\n];\n`,
);
console.log(
  "wygenerowano receptur:",
  extra.length,
  "| lepszych bez receptury było:",
  better.length,
);
const byStation: Record<string, number> = {};
for (const r of extra) byStation[r.station] = (byStation[r.station] ?? 0) + 1;
console.log("wg stacji:", JSON.stringify(byStation));
